/**
 * Generates the shared premium voice clips and bundles them with the app.
 *
 * Run after changing shared phrases (globalPackClips) or a voice:
 *   npx tsx scripts/bundle-voice-clips.ts
 *
 * Writes assets/voice/<voiceId>/<hash>.mp3 and src/audio/bundledClips.ts.
 */

import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { globalPackClips } from '../src/audio/cuePhrases';
import { type Clip, clipKey, toClipRequest } from '../src/audio/clipKey';
import { PREMIUM_VOICES } from '../src/audio/voiceCatalog';

const ROOT = resolve(__dirname, '..');
const BATCH_SIZE = 50;

function supabaseConfig(): { url: string; anonKey: string } {
  const src = readFileSync(join(ROOT, 'src/analytics/supabaseClient.ts'), 'utf8');
  const url = src.match(/SUPABASE_URL\s*=\s*'([^']+)'/)?.[1];
  const anonKey = src.match(/SUPABASE_ANON_KEY\s*=\s*'([^']+)'/)?.[1];
  if (!url || !anonKey) throw new Error('Could not read Supabase config from supabaseClient.ts');
  return { url, anonKey };
}

async function fetchClipUrls(voiceId: string, clips: Clip[]): Promise<Map<string, string>> {
  const { url, anonKey } = supabaseConfig();
  const urls = new Map<string, string>();
  for (let i = 0; i < clips.length; i += BATCH_SIZE) {
    const batch = clips.slice(i, i + BATCH_SIZE);
    const res = await fetch(`${url}/functions/v1/voice-clips`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${anonKey}`, apikey: anonKey, 'Content-Type': 'application/json' },
      body: JSON.stringify({ voiceId, clips: batch.map(toClipRequest) }),
    });
    if (!res.ok) throw new Error(`voice-clips ${res.status}: ${await res.text()}`);
    const data = (await res.json()) as { clips: { key: string; url: string | null }[] };
    for (const c of data.clips) if (c.url) urls.set(c.key, c.url);
    console.log(`  ${voiceId}: ${Math.min(i + BATCH_SIZE, clips.length)}/${clips.length} requested`);
  }
  return urls;
}

async function main() {
  const entries: string[] = [];
  let totalBytes = 0;
  let missing = 0;

  for (const voice of PREMIUM_VOICES) {
    const unique = new Map<string, Clip>();
    for (const clip of [...globalPackClips('minPerMile'), ...globalPackClips('minPerKm')]) {
      unique.set(clipKey(clip), clip);
    }
    const clips = [...unique.values()];
    console.log(`${voice.id}: ${clips.length} shared clips`);

    const urls = await fetchClipUrls(voice.id, clips);
    const dir = join(ROOT, 'assets/voice', voice.id);
    if (existsSync(dir)) rmSync(dir, { recursive: true });
    mkdirSync(dir, { recursive: true });

    const lines: string[] = [];
    for (const [key, url] of urls) {
      const fileName = url.split('/').pop()!;
      const res = await fetch(url);
      if (!res.ok) throw new Error(`Download failed ${res.status}: ${url}`);
      writeFileSync(join(dir, fileName), Buffer.from(await res.arrayBuffer()));
      lines.push(`    ${JSON.stringify(key)}: require('../../assets/voice/${voice.id}/${fileName}'),`);
    }
    missing += clips.length - urls.size;
    for (const f of readdirSync(dir)) totalBytes += statSync(join(dir, f)).size;
    entries.push(`  ${JSON.stringify(voice.id)}: {\n${lines.sort().join('\n')}\n  },`);
  }

  writeFileSync(
    join(ROOT, 'src/audio/bundledClips.ts'),
    [
      '// Generated by scripts/bundle-voice-clips.ts. Do not edit by hand.',
      '',
      '/** voiceId → clip key → bundled asset */',
      'export const BUNDLED_CLIPS: Record<string, Record<string, number>> = {',
      ...entries,
      '};',
      '',
    ].join('\n'),
  );

  console.log(`Bundled ${(totalBytes / 1024 / 1024).toFixed(2)} MB of voice clips.`);
  if (missing > 0) {
    console.warn(`${missing} clips failed to generate; re-run to fill them in.`);
    process.exitCode = 1;
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
